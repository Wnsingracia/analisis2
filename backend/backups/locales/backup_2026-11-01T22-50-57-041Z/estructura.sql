-- ESTRUCTURA DE VETCARE
-- Esquema public
CREATE SCHEMA IF NOT EXISTS public;

CREATE SEQUENCE IF NOT EXISTS public."auditoria_id_evento_seq"
    AS bigint
    INCREMENT BY 1
    MINVALUE 1
    MAXVALUE 9223372036854775807
    START WITH 1
    CACHE 1
    NO CYCLE;

CREATE SEQUENCE IF NOT EXISTS public."seq_id_clientes"
    AS bigint
    INCREMENT BY 1
    MINVALUE 700001
    MAXVALUE 9223372036854775807
    START WITH 700001
    CACHE 1
    NO CYCLE;

CREATE SEQUENCE IF NOT EXISTS public."seq_id_personal"
    AS bigint
    INCREMENT BY 1
    MINVALUE 100001
    MAXVALUE 9223372036854775807
    START WITH 100001
    CACHE 1
    NO CYCLE;

CREATE TABLE IF NOT EXISTS public."administradores" (
    "id_usuario" bigint NOT NULL,
    "nvl_acceso" text
);

CREATE TABLE IF NOT EXISTS public."auditoria" (
    "id_evento" bigint DEFAULT nextval('auditoria_id_evento_seq'::regclass) NOT NULL,
    "fecha" timestamp with time zone DEFAULT now() NOT NULL,
    "id_usuario" bigint,
    "rol" text,
    "evento" text NOT NULL,
    "recurso" text,
    "resultado" text NOT NULL,
    "ip" text,
    "detalle" jsonb
);

CREATE TABLE IF NOT EXISTS public."citas" (
    "id_cita" bigint NOT NULL,
    "fecha" text,
    "hora" text,
    "tipo" text,
    "descripcion" text,
    "costo" double precision,
    "id_mascota" bigint,
    "id_cliente" bigint,
    "id_recepcionista" bigint
);

CREATE TABLE IF NOT EXISTS public."clientes" (
    "id_usuario" bigint NOT NULL,
    "nro_cuenta" text,
    "direccion" text,
    "nit" bigint
);

CREATE TABLE IF NOT EXISTS public."consultas" (
    "id_cons_medica" bigint NOT NULL,
    "fecha" text,
    "hora" text,
    "costo" double precision,
    "especialidad" text,
    "ambiente" text,
    "id_veterinario" bigint,
    "id_cita" bigint,
    "idMascota" bigint
);

CREATE TABLE IF NOT EXISTS public."empleados" (
    "id_usuario" bigint NOT NULL,
    "salario" double precision,
    "hora_ingreso" text,
    "hora_salida" text
);

CREATE TABLE IF NOT EXISTS public."estilistas" (
    "id_usuario" bigint NOT NULL,
    "rol" text
);

CREATE TABLE IF NOT EXISTS public."mascotas" (
    "id_mascota" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "id_cliente" bigint NOT NULL,
    "nombre" text,
    "tipo" text,
    "raza" text,
    "edad" bigint,
    "peso" double precision,
    "altura" double precision,
    "alergias" text,
    "genero" text
);

CREATE TABLE IF NOT EXISTS public."recepcionistas" (
    "id_usuario" bigint NOT NULL,
    "departamento" text
);

CREATE TABLE IF NOT EXISTS public."tratamientos" (
    "id_tratamiento" bigint NOT NULL,
    "descripcion" text,
    "fecha_emision" text,
    "id_cons_medica" bigint
);

CREATE TABLE IF NOT EXISTS public."usuarios" (
    "id_usuario" bigint NOT NULL,
    "nombres" text,
    "ap_pat" text,
    "ap_mat" text,
    "cel" bigint,
    "correo" text,
    "genero" text,
    "contrasenia" text,
    "tipo_usuario" text,
    "reset_token" text,
    "reset_token_expira" text,
    "intentos_fallidos" bigint,
    "bloqueado_hasta" text,
    "fecha_creacion" timestamp with time zone,
    "estado" text DEFAULT 'ACTIVA'::text NOT NULL,
    "motivo_estado" text,
    "fecha_estado" timestamp with time zone,
    "token_version" integer DEFAULT 0 NOT NULL,
    "totp_secreto" text,
    "totp_activo" boolean DEFAULT false NOT NULL,
    "totp_ultimo_paso" bigint,
    "es_emergencia" boolean DEFAULT false NOT NULL
);

CREATE TABLE IF NOT EXISTS public."veterinarios" (
    "id_usuario" bigint NOT NULL,
    "especializacion" text,
    "titulo" text
);
